"""Write docs/cli.md, the CLI reference, from the command definitions (MADIV-28 T8.3).

python scripts/generate_cli_reference.py            # writes docs/cli.md
python scripts/generate_cli_reference.py --stdout   # prints it instead

tests/unit/test_cli_reference.py fails when docs/cli.md is out of date.
"""

from __future__ import annotations

import sys
from importlib import import_module
from pathlib import Path
from typing import Any

import typer
from typer.cli import get_docs_for_click

REPO = Path(__file__).resolve().parents[1]
TARGET = REPO / "docs" / "cli.md"

HEADER = """# ALMASim command-line reference

<!-- Generated by scripts/generate_cli_reference.py from the command
definitions; edit those and rerun the script instead of this file. -->

`almasim` has {groups} command groups and {singles} single commands. Each
group's commands are listed with their arguments and options. Hidden
commands (kept for compatibility) are left out.
"""


_COMPLETION_OPTIONS = ("* `--install-completion`", "* `--show-completion`")


def _without_hidden(command: Any) -> Any:
    """``command`` with its hidden subcommands (compatibility aliases) dropped.

    Typer vendors its own click, so groups are recognised by their ``commands``.
    """
    if isinstance(getattr(command, "commands", None), dict):
        command.commands = {
            name: _without_hidden(sub) for name, sub in command.commands.items() if not sub.hidden
        }
    return command


def _one_level_down(text: str) -> str:
    """``text`` with every heading outside code blocks one level deeper.

    Typer titles each command ``#``; under the page's own ``#`` they must be
    ``##`` (and their subcommands ``###``), or the docs sidebar lists every
    command as a page of its own.
    """
    lines = []
    in_code = False
    for line in text.splitlines(keepends=True):
        if line.startswith("```"):
            in_code = not in_code
        elif not in_code and line.startswith("#"):
            line = "#" + line
        lines.append(line)
    return "".join(lines)


def _document(command: Any, name: str) -> str:
    command = _without_hidden(command)
    return _one_level_down(
        get_docs_for_click(
            obj=command,
            ctx=typer.Context(command, info_name=name),
            name=name,
            title=f"`{name}`",
        )
    )


def render() -> str:
    from almasim.cli import _GROUPS

    top = import_module("almasim.cli")
    singles = (
        ("doctor", top.doctor_command),
        ("update-shared", top.update_shared_command),
        ("submit", top.submit_command),
        ("serve", top.serve_command),
    )
    # and clean, documented below from its own module
    parts = [HEADER.format(groups=len(_GROUPS), singles=len(singles) + 1)]
    for name, module_name, app_name, _help in _GROUPS:
        module = import_module(module_name, "almasim.cli")
        parts.append(
            _document(typer.main.get_command(getattr(module, app_name)), f"almasim {name}")
        )
    clean = typer.Typer(add_completion=False)
    clean.command("clean")(import_module("almasim.cli.clean").clean_command)
    parts.append(_document(typer.main.get_command(clean), "almasim clean"))
    for name, function in singles:
        single = typer.Typer(add_completion=False)
        single.command(name)(function)
        parts.append(_document(typer.main.get_command(single), f"almasim {name}"))
    text = "\n".join(part.rstrip() + "\n" for part in parts)
    # The sub-apps' shell-completion options are not reachable through almasim.
    text = "".join(
        line for line in text.splitlines(keepends=True) if not line.startswith(_COMPLETION_OPTIONS)
    )
    # Defaults derived from the checkout or the home directory, shown portably.
    return text.replace(str(REPO), "<repo>").replace(str(Path.home()), "~")


def main() -> None:
    text = render()
    if "--stdout" in sys.argv[1:]:
        sys.stdout.write(text)
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")


if __name__ == "__main__":
    main()
